import re,base64
from pathlib import Path
from playwright.sync_api import sync_playwright
base=Path('/mnt/data/angaya_edit/jeu')
index=(base/'index.html').read_text()
styles='\n'.join(re.findall(r'<style[^>]*>(.*?)</style>',index,flags=re.S))+'\n'+(base/'angaya-chronicles.css').read_text()
core=(base/'angaya-game-core.js').read_text()
core=re.sub(r'([\x27\x22])data:[^\x27\x22\n]{1,110};base64,[A-Za-z0-9+/=]{256,}\1','""',core)
print('core test bytes',len(core),flush=True)
html=f'<!doctype html><html lang="fr"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>{styles}</style></head><body><div id="app" class="app-shell"><header class="topbar">ANGAYA CRUSH</header><main id="screen" role="main"></main><nav id="bottom-nav" class="bottom-nav"><button class="nav-item" data-action="home">⌂<span>Accueil</span></button><button class="nav-item" data-action="map">🗺️<span>Niveaux</span></button><button class="nav-item" data-action="gallery">📷<span>Galerie</span></button><button class="nav-item" data-action="profile">👤<span>Profil</span></button><button class="nav-item" data-action="settings">⚙<span>Réglages</span></button></nav><div id="modal-root"></div><div id="toast"></div></div></body></html>'
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(html,wait_until='domcontentloaded')
 page.evaluate('window.ANGAYA_PLAYER={id:"TEST_PERSON",email:"test@example.test",name:""}')
 page.add_script_tag(content=core)
 chronicle=(base/'angaya-chronicles.js').read_text()
 cover='data:image/webp;base64,'+base64.b64encode((base/'assets/creators-angaya.webp').read_bytes()).decode()
 chronicle=chronicle.replace('./assets/creators-angaya.webp',cover)
 page.add_script_tag(content=chronicle)
 print('loaded',page.evaluate('({state:state.username,hasProfile:!!window.AngayaChronicles})'),flush=True)
 page.locator('#angaya-name-field').fill('Manoa Test')
 page.locator('.angaya-name-start').click()
 page.locator('[data-action="profile"]').last.click()
 print('profile',page.locator('.angaya-profile-chapter').count(),flush=True)
 page.screenshot(path='/mnt/data/angaya_edit/profile_test.png')
 page.evaluate('''() => {state.nextLevel=5;state.chapterScores[0]=1280;state.careerScore=1280;state.adventureHistory=[{at:new Date().toISOString(),level:4,chapter:0,won:true,score:340,bonus:55,movesUsed:20,stars:3,replay:false,usedTools:{coconut:1,hint:1}}];save();setPage('home',true);window.AngayaChronicles.showPalierSummary(0,{level:4,stars:3,reward:70,nextLevel:5,final:false});}''')
 print('summary',page.locator('.angaya-palier-summary button').count(),flush=True)
 page.wait_for_timeout(600)
 page.screenshot(path='/mnt/data/angaya_edit/summary_test.png')
 page.evaluate('''() => {state.nextLevel=TOTAL_LEVELS+1;state.careerScore=206300;state.careerGames=225;window.AngayaChronicles.launchFinale();}''')
 print('story',page.locator('.angaya-story-chapter').count(),flush=True)
 page.screenshot(path='/mnt/data/angaya_edit/story_open_test.png')
 page.locator('#angaya-cinema').click(position={'x':150,'y':300})
 print('skip done',page.locator('.angaya-story-complete').count(),flush=True)
 page.wait_for_timeout(3550)
 print('home visible',page.locator('#angaya-cinema-home').is_visible(),flush=True)
 page.screenshot(path='/mnt/data/angaya_edit/story_end_test.png')
 page.locator('#angaya-cinema-home').click()
 print('end',page.locator('#angaya-cinema').count(),page.locator('.new-hero').count(),flush=True)
 print('errors',errors,flush=True)
 browser.close()
